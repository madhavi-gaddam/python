#ARITHEMATIC OPERATORS
a = 10
b = 3

print(a + b)   # 13 (Addition)
print(a - b)   # 7  (Subtraction)
print(a * b)   # 30 (Multiplication)
print(a / b)   # 3.33 (Division)
print(a // b)  # 3 (Floor Division)
print(a % b)   # 1 (Modulus)
print(a ** b)  # 1000 (Power)

#COMPARISION OPERATORS
a = 5
b = 10

print(a == b)  # False
print(a != b)  # True
print(a > b)   # False
print(a < b)   # True
print(a >= b)  # False
print(a <= b)  # True

#LOGICAL OPERATORS
x = True
y = False

print(x and y)  # False
print(x or y)   # True
print(not x)    # False


#BITWISE OPERATORS
a = 5   # 101
b = 3   # 011

print(a & b)  # 1 (AND)
print(a | b)  # 7 (OR)
print(a ^ b)  # 6 (XOR)
print(~a)     # -6 (NOT)
print(a << 1) # 10 (Left shift)
print(a >> 1) # 2  (Right shift)




