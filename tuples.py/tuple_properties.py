#A tuple is a collection of items packed with closed brackets

#Immutable You cannot change values after creation

t = (10, 20, 30)
print(t[0])  # 10

#allows duplicates
t = (1, 2, 2, 3)
print(t)  # (1, 2, 2, 3)


#can store different data types
t = (1, "hello", 3.5, True)


#indexing and slicing
t = (10, 20, 30, 40)

print(t[1])     # 20
print(t[-1])    # 40
print(t[1:3])   # (20, 30)





